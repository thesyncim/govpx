// The entry point proves a disjoint 20x16 tile. Only columns 1..17 change;
// retaining finalized columns lets us write 16 bytes per row and one tail byte.
func packMacroFilterRows(body string) string {
	formatted, err := format.Source([]byte("package pixel\n" + body))
	if err != nil {
		panic(err)
	}
	body = strings.TrimPrefix(string(formatted), "package pixel\n\n")
	replace := func(old, new string) {
		if strings.Count(body, old) != 1 {
			panic("row-store marker changed: " + old)
		}
		body = strings.Replace(body, old, new, 1)
	}
	const load = "p3, p2, p1, p0, q0, q1, q2, q3 := loadLFColumns[[8]byte](p, 0, outer, 16)"
	replace(load, load+"\nvar output [16]archsimd.Uint8x16\noutput[0],output[1],output[2]=p2,p1,p0\nchanged:=false")
	replace("\n\t\toff := 4 * step", "")
	first := strings.Index(body, "\n\t\t\t\t{\n\t\t\t\t\tptr :=")
	last := strings.Index(body, "\n\t\t\t\tq0, q1, q2 = nq0, nq1, nq2")
	if first < 0 || last < first {
		panic("macro row-store markers missing")
	}
	body = body[:first] + "\noutput[0],output[1],output[2]=np2,np1,np0\nchanged=true\n" + body[last:]
	const loop = "for edge := 8; edge <= 16; edge += 4 {"
	replace(loop, loop+"\noutput[edge-5],output[edge-4],output[edge-3],output[edge-2]=p3,p2,p1,p0")
	first = strings.Index(body, "\n\t\t\t// The caller proves the complete 16x16 window.")
	last = strings.Index(body, "\n\t\t\tq0, q1 = nq0, nq1")
	if first < 0 || last < first {
		panic("internal row-store markers missing")
	}
	body = body[:first] + "\noutput[edge-3],output[edge-2]=np1,np0\nchanged=true\n" + body[last:]
	last = strings.LastIndex(body, "\n}")
	if last < 0 {
		panic("row-store function end missing")
	}
	return body[:last] + "\nif changed {\noutput[15]=q0\nstoreLFRowVectors(p,pitch,&output,q1)\n}\n" + body[last:]
}
func generateLoopFilterRowStore() {
	var out strings.Builder
	out.WriteString(`//go:build goexperiment.simd && arm64 && !purego

// Code generated by go run scripts/gensimd.go; DO NOT EDIT.
package pixel
import("simd/archsimd";"unsafe")
// storeLFRowVectors transposes sixteen finalized columns into row stores.
// The caller proves disjoint rows and a complete 20x16 tile; these stores
// touch exactly columns 1..17, preserving the three surrounding columns.
func storeLFRowVectors(p []byte,pitch int,cols *[16]archsimd.Uint8x16,tail archsimd.Uint8x16) {
`)
	groups := make([][]string, 16)
	for i := range groups {
		groups[i] = []string{fmt.Sprintf("cols[%d]", i)}
	}
	for stage, cast := range []string{"", ".ReshapeToUint16s()", ".ReshapeToUint32s()", ".ReshapeToUint64s()"} {
		var next [][]string
		reshape := ""
		if stage != 0 {
			reshape = ".ReshapeToUint8s()"
		}
		for g := 0; g < len(groups); g += 2 {
			var values []string
			for j, a := range groups[g] {
				for _, half := range []string{"Lo", "Hi"} {
					name := fmt.Sprintf("t%d_%d_%d_%s", stage, g, j, half)
					fmt.Fprintf(&out, "%s:=%s%s.Interleave%s(%s%s)%s\n", name, a, cast, half, groups[g+1][j], cast, reshape)
					values = append(values, name)
				}
			}
			next = append(next, values)
		}
		groups = next
	}
	out.WriteString("ptr:=unsafe.Pointer(unsafe.SliceData(p))\n")
	for i, v := range groups[0] {
		fmt.Fprintf(&out, "%s.StoreArray((*[16]byte)(unsafe.Add(ptr,%d*pitch+1)))\np[%d*pitch+17]=tail.GetElem(%d)\n", v, i, i, i)
	}
	out.WriteString("}\n")
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("internal/pixel/loopfilter_rowstore_arm64.go", data, 0644); err != nil {
		panic(err)
	}
}
